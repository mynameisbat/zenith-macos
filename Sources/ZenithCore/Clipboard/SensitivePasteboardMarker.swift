import Foundation
import AppKit

/// Known markers set by password managers, privacy utilities, and transient clipboard generators.
public enum SensitivePasteboardMarker {
    // Standard Password Managers
    public static let concealedType = NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType")
    public static let onePassword = NSPasteboard.PasteboardType("com.agilebits.onepassword")
    public static let lastPass = NSPasteboard.PasteboardType("com.lastpass.LastPassFormFiller")
    public static let keePassX = NSPasteboard.PasteboardType("de.keepassx.clipmarker")
    public static let keeWeb = NSPasteboard.PasteboardType("net.antelle.keeweb")

    // Extended Password Managers (HIGH-07)
    public static let keepassXC = NSPasteboard.PasteboardType("de.keepassxc.keepassxc")
    public static let bitwarden = NSPasteboard.PasteboardType("com.bitwarden.desktop")
    public static let keepassXCOrg = NSPasteboard.PasteboardType("org.keepassxc.keepassxc")

    // Transient & Auto-generated Content
    public static let autoGeneratedType = NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")
    public static let transientType = NSPasteboard.PasteboardType("org.nspasteboard.TransientType")
    public static let legacyTransientType = NSPasteboard.PasteboardType("de.petermaurer.TransientPasteboardType")
    public static let typeIt4Me = NSPasteboard.PasteboardType("com.typeit4me.clipping")
    public static let pasteboardGeneratorType = NSPasteboard.PasteboardType("Pasteboard generator type")

    /// The original 10 canonical sensitive markers (backward-compatible with tests).
    public static let allMarkers: Set<NSPasteboard.PasteboardType> = [
        concealedType,
        onePassword,
        lastPass,
        keePassX,
        keeWeb,
        autoGeneratedType,
        transientType,
        legacyTransientType,
        typeIt4Me,
        pasteboardGeneratorType
    ]

    /// The exact 10 original sensitive UTI strings (backward-compatible with tests and legacy consumers).
    /// Invariant: Must strictly have count == 10 to satisfy ADV-M7-16.
    public static let sensitiveTypes: [String] = [
        "org.nspasteboard.ConcealedType",
        "com.agilebits.onepassword",
        "com.lastpass.LastPassFormFiller",
        "de.keepassx.clipmarker",
        "net.antelle.keeweb",
        "org.nspasteboard.AutoGeneratedType",
        "org.nspasteboard.TransientType",
        "de.petermaurer.TransientPasteboardType",
        "com.typeit4me.clipping",
        "Pasteboard generator type"
    ]

    /// Extended sensitive types filtered by Zenith (KeePassXC, Bitwarden, MacPass, Enpass, etc.)
    public static let extendedSensitiveTypes: [String] = [
        "de.keepassxc.keepassxc",
        "com.bitwarden.desktop",
        "org.keepassxc.keepassxc",
        "com.bitwarden.clipmarker",
        "org.macpassapp.macpass",
        "in.sinew.enpass-desktop",
        "application/x-nspasteboard-concealed-type"
    ]

    /// Normalized lowercase set containing all original + extended markers for O(1) case-insensitive lookup.
    @usableFromInline
    internal static let normalizedSensitiveSet: Set<String> = {
        var set = Set<String>()
        for m in allMarkers {
            set.insert(m.rawValue.trimmingCharacters(in: .whitespacesAndNewlines).lowercased())
        }
        for s in sensitiveTypes {
            set.insert(s.trimmingCharacters(in: .whitespacesAndNewlines).lowercased())
        }
        for s in extendedSensitiveTypes {
            set.insert(s.trimmingCharacters(in: .whitespacesAndNewlines).lowercased())
        }
        return set
    }()

    /// Determines whether the given list of types contains any sensitive or transient marker (case-insensitive).
    @inlinable
    public static func containsSensitiveType(in types: [NSPasteboard.PasteboardType]) -> Bool {
        for type in types {
            let lower = type.rawValue.trimmingCharacters(in: .whitespacesAndNewlines).lowercased()
            if normalizedSensitiveSet.contains(lower) {
                return true
            }
        }
        return false
    }

    /// Single type convenience check matching pasteboard types (case-insensitive).
    @inlinable
    public static func containsSensitiveType(type: NSPasteboard.PasteboardType) -> Bool {
        containsSensitiveType(in: [type])
    }

    /// Unified convenience check matching string identifiers (case-insensitive).
    public static func isSensitive(types: [String]) -> Bool {
        for type in types {
            let lower = type.trimmingCharacters(in: .whitespacesAndNewlines).lowercased()
            if normalizedSensitiveSet.contains(lower) {
                return true
            }
        }
        return false
    }

    /// Single type convenience check matching string identifiers (case-insensitive).
    public static func isSensitive(type: String) -> Bool {
        isSensitive(types: [type])
    }

    /// Unified convenience check matching pasteboard types.
    public static func isSensitive(types: [NSPasteboard.PasteboardType]) -> Bool {
        containsSensitiveType(in: types)
    }
}
