import Testing
import Foundation
import AppKit
@testable import ZenithCore

/// Collects what a monitor hands over, from whatever queue it does.
private final class CaptureRecorder: @unchecked Sendable {
    private let lock = NSLock()
    private var _items: [ClipboardItem] = []

    func record(_ item: ClipboardItem) { lock.withLock { _items.append(item) } }
    var items: [ClipboardItem] { lock.withLock { _items } }

    /// Waits (at most ~2 s, in 10 ms steps) until `count` items arrived.
    func wait(for count: Int) async {
        for _ in 0..<200 where items.count < count {
            try? await Task.sleep(nanoseconds: 10_000_000)
        }
    }
}

@MainActor
private final class ChangeRecorder {
    var counts: [Int] = []
}

@Suite("Clipboard capture policy: sensitive copies, ignored apps, link rewriting")
struct ClipboardCapturePolicyTests {

    // MARK: - Pure decisions

    @Test("Concealed, transient and auto-generated markers are never recorded")
    func testSensitiveMarkersSkip() {
        let options = ClipboardCaptureOptions()
        for marker in ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType"] {
            #expect(ClipboardCapturePolicy.decide(types: ["public.utf8-plain-text", marker], frontmostBundleIdentifier: nil, options: options) == .skipSensitive)
            // A marker on one pasteboard item is enough.
            #expect(ClipboardCapturePolicy.decide(types: ["public.utf8-plain-text"], itemTypes: [["public.utf8-plain-text"], [marker]], frontmostBundleIdentifier: nil, options: options) == .skipSensitive)
        }
        #expect(ClipboardCapturePolicy.decide(types: ["public.utf8-plain-text"], frontmostBundleIdentifier: nil, options: options) == .record)
    }

    @Test("Copies made while an ignored app is in front are skipped, compared without case")
    func testIgnoredAppSkips() {
        let options = ClipboardCaptureOptions(ignoredBundleIdentifiers: ["com.1password.1password", "Org.KeePassXC.KeePassXC"])
        #expect(ClipboardCapturePolicy.decide(types: ["public.utf8-plain-text"], frontmostBundleIdentifier: "com.1password.1password", options: options) == .skipIgnoredApp("com.1password.1password"))
        #expect(ClipboardCapturePolicy.decide(types: ["public.utf8-plain-text"], frontmostBundleIdentifier: "org.keepassxc.KeePassXC", options: options) == .skipIgnoredApp("org.keepassxc.KeePassXC"))
        #expect(ClipboardCapturePolicy.decide(types: ["public.utf8-plain-text"], frontmostBundleIdentifier: "com.apple.Safari", options: options) == .record)
        #expect(ClipboardCapturePolicy.decide(types: ["public.utf8-plain-text"], frontmostBundleIdentifier: nil, options: options) == .record)
    }

    @Test("A link is rewritten only when it is the whole copy, has tracking, and nothing else would be lost")
    func testCleanedLinkRewriteDecision() {
        let tracked = "https://example.com/a?utm_source=x&id=3"
        #expect(ClipboardCapturePolicy.cleanedLinkRewrite(types: ["public.utf8-plain-text"], string: tracked) == "https://example.com/a?id=3")
        #expect(ClipboardCapturePolicy.cleanedLinkRewrite(types: ["public.utf8-plain-text", "public.url", "public.url-name"], string: tracked) == "https://example.com/a?id=3")
        // Whitespace around the link stays.
        #expect(ClipboardCapturePolicy.cleanedLinkRewrite(types: ["public.utf8-plain-text"], string: " \(tracked)\n") == " https://example.com/a?id=3\n")
        // Rich text, HTML, a file or an image would be lost: leave the copy alone.
        #expect(ClipboardCapturePolicy.cleanedLinkRewrite(types: ["public.utf8-plain-text", "public.rtf"], string: tracked) == nil)
        #expect(ClipboardCapturePolicy.cleanedLinkRewrite(types: ["public.utf8-plain-text", "public.html"], string: tracked) == nil)
        #expect(ClipboardCapturePolicy.cleanedLinkRewrite(types: ["public.file-url", "public.utf8-plain-text"], string: tracked) == nil)
        #expect(ClipboardCapturePolicy.cleanedLinkRewrite(types: ["public.utf8-plain-text", "com.example.private"], string: tracked) == nil)
        // Nothing to clean, more than one link, or not a link.
        #expect(ClipboardCapturePolicy.cleanedLinkRewrite(types: ["public.utf8-plain-text"], string: "https://example.com/a?id=3") == nil)
        #expect(ClipboardCapturePolicy.cleanedLinkRewrite(types: ["public.utf8-plain-text"], string: "see \(tracked)") == nil)
        #expect(ClipboardCapturePolicy.cleanedLinkRewrite(types: ["public.utf8-plain-text"], string: nil) == nil)
        #expect(ClipboardCapturePolicy.cleanedLinkRewrite(types: [], string: tracked) == nil)
    }

    // MARK: - The monitor, on a private pasteboard

    @MainActor
    private func makeMonitor(frontmost: String? = nil, options: ClipboardCaptureOptions = ClipboardCaptureOptions())
        -> (PasteboardMonitor, NSPasteboard, CaptureRecorder, ChangeRecorder) {
        let pasteboard = NSPasteboard.withUniqueName()
        let monitor = PasteboardMonitor(
            pasteboard: pasteboard,
            pollingInterval: 3_600, // never polls by itself; the test calls checkForChanges()
            frontmostApplication: MockFrontmostApplicationProvider(bundleIdentifier: frontmost)
        )
        monitor.captureOptions = options
        let recorder = CaptureRecorder()
        let changes = ChangeRecorder()
        monitor.changeObserver = { count in changes.counts.append(count) }
        monitor.startMonitoring { item in recorder.record(item) }
        return (monitor, pasteboard, recorder, changes)
    }

    @MainActor
    @Test("Monitor: a concealed copy is not recorded but still reported as a change")
    func testMonitorSkipsConcealedCopy() async {
        let (monitor, pasteboard, recorder, changes) = makeMonitor()
        defer { monitor.stopMonitoring(); pasteboard.releaseGlobally() }

        pasteboard.clearContents()
        pasteboard.setString("hunter2", forType: .string)
        pasteboard.setData(Data(), forType: NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType"))
        monitor.checkForChanges()

        #expect(recorder.items.isEmpty)
        #expect(changes.counts == [pasteboard.changeCount])
    }

    @MainActor
    @Test("Monitor: a copy made in an ignored app is not recorded; another app's is")
    func testMonitorSkipsIgnoredApp() async {
        let provider = MockFrontmostApplicationProvider(bundleIdentifier: "com.bitwarden.desktop")
        let pasteboard = NSPasteboard.withUniqueName()
        let monitor = PasteboardMonitor(pasteboard: pasteboard, pollingInterval: 3_600, frontmostApplication: provider)
        monitor.captureOptions = ClipboardCaptureOptions(ignoredBundleIdentifiers: ["com.bitwarden.desktop"])
        let recorder = CaptureRecorder()
        monitor.startMonitoring { item in recorder.record(item) }
        defer { monitor.stopMonitoring(); pasteboard.releaseGlobally() }

        pasteboard.clearContents()
        pasteboard.setString("secret-from-bitwarden", forType: .string)
        monitor.checkForChanges()
        #expect(recorder.items.isEmpty)

        provider.bundleIdentifier = "com.apple.TextEdit"
        pasteboard.clearContents()
        pasteboard.setString("ordinary text", forType: .string)
        monitor.checkForChanges()
        await recorder.wait(for: 1)
        #expect(recorder.items.map(\.plainTextContent) == ["ordinary text"])
    }

    @MainActor
    @Test("Monitor: a tracked link is rewritten once, recorded cleaned, and the rewrite is not seen as a new copy")
    func testMonitorCleansLinkWithoutLoop() async {
        let (monitor, pasteboard, recorder, changes) = makeMonitor(options: ClipboardCaptureOptions(cleanLinksOnCopy: true))
        defer { monitor.stopMonitoring(); pasteboard.releaseGlobally() }

        let tracked = "https://news.example.com/story?id=42&utm_source=twitter&fbclid=IwAR0"
        pasteboard.clearContents()
        pasteboard.setString(tracked, forType: .string)
        pasteboard.setString(tracked, forType: .URL)
        pasteboard.setString("A Story", forType: NSPasteboard.PasteboardType("public.url-name"))
        let countBefore = pasteboard.changeCount
        monitor.checkForChanges()

        #expect(pasteboard.string(forType: .string) == "https://news.example.com/story?id=42")
        #expect(pasteboard.string(forType: .URL) == "https://news.example.com/story?id=42")
        #expect(pasteboard.string(forType: NSPasteboard.PasteboardType("public.url-name")) == "A Story")
        #expect(pasteboard.changeCount > countBefore)
        #expect(changes.counts == [pasteboard.changeCount])

        await recorder.wait(for: 1)
        #expect(recorder.items.map(\.plainTextContent) == ["https://news.example.com/story?id=42"])

        // The rewrite is Zenith's own: the next look finds nothing new, so nothing is cleaned or stored twice.
        monitor.checkForChanges()
        try? await Task.sleep(nanoseconds: 50_000_000)
        #expect(recorder.items.count == 1)
        #expect(changes.counts.count == 1)
    }

    @MainActor
    @Test("Monitor: link cleaning is off by default and never rewrites rich text")
    func testMonitorLeavesLinksAloneWhenOffOrRich() async {
        let tracked = "https://example.com/?utm_source=x"

        let (plainMonitor, plainBoard, plainRecorder, _) = makeMonitor()
        plainBoard.clearContents()
        plainBoard.setString(tracked, forType: .string)
        plainMonitor.checkForChanges()
        await plainRecorder.wait(for: 1)
        #expect(plainBoard.string(forType: .string) == tracked)
        #expect(plainRecorder.items.map(\.plainTextContent) == [tracked])
        plainMonitor.stopMonitoring(); plainBoard.releaseGlobally()

        let (richMonitor, richBoard, richRecorder, _) = makeMonitor(options: ClipboardCaptureOptions(cleanLinksOnCopy: true))
        let rtf = Data("{\\rtf1\\ansi \(tracked)}".utf8)
        richBoard.clearContents()
        richBoard.setData(rtf, forType: .rtf)
        richBoard.setString(tracked, forType: .string)
        richMonitor.checkForChanges()
        await richRecorder.wait(for: 1)
        #expect(richBoard.string(forType: .string) == tracked)
        #expect(richBoard.data(forType: .rtf) == rtf)
        #expect(richRecorder.items.first?.itemType == .richText)
        richMonitor.stopMonitoring(); richBoard.releaseGlobally()
    }

    @MainActor
    @Test("Monitor: Zenith's own writes are reported to the change observer and never recorded")
    func testMonitorReportsOwnWrites() async {
        let (monitor, pasteboard, recorder, changes) = makeMonitor()
        defer { monitor.stopMonitoring(); pasteboard.releaseGlobally() }

        monitor.copyItemToPasteboard(.text("from history"))
        #expect(changes.counts == [pasteboard.changeCount])
        monitor.checkForChanges()
        // clear() is not a copy: no report.
        monitor.clear()
        #expect(changes.counts.count == 1)
        try? await Task.sleep(nanoseconds: 50_000_000)
        #expect(recorder.items.isEmpty)
    }
}
